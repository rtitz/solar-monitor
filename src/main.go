package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"solar-monitor/generalUtils"
	"solar-monitor/homeassistantApi"
	"solar-monitor/prometheus"
	"solar-monitor/rctApi"
	"solar-monitor/rctUtils"
	"solar-monitor/variables"
	"strconv"
	"strings"
	"time"
)

func main() {
	fmt.Printf("%s %s (%s/%s)\n\n", variables.AppName, variables.AppVersion, variables.GOOS, variables.GOARCH)
	var c *rctApi.Connection
	var err error

	maxRetries := 0               // 0 means retry indefinitely
	retryDelay := time.Second * 2 // Initial wait time between retries

	for attempt := 1; maxRetries == 0 || attempt <= maxRetries; attempt++ {
		fmt.Printf("Connecting to inverter at %s:%s (Attempt %d/%s)...\n", variables.InverterIp, variables.InverterPort, attempt, func() string {
			if maxRetries == 0 {
				return "∞"
			}
			return strconv.Itoa(maxRetries)
		}())

		c, err = rctApi.NewConnection(variables.InverterIp, time.Second*2)
		if err == nil {
			fmt.Println("Successfully connected to inverter!")
			break
		}

		fmt.Printf("Connection failed: %v\n", err)

		if attempt < maxRetries || maxRetries == 0 {
			fmt.Printf("Retrying in %v...\n", retryDelay)
			time.Sleep(retryDelay)
			retryDelay *= 2 // Exponential backoff: 2s, 4s, 8s, 16s...
		}
	}

	// If all retry attempts failed, exit the application cleanly
	if err != nil {
		fmt.Printf("Error: Could not connect to inverter after %s attempts: %v\n", func() string {
			if maxRetries == 0 {
				return "∞"
			}
			return strconv.Itoa(maxRetries)
		}(), err)
		return
	}
	defer c.Close()

	time.Sleep(time.Millisecond * time.Duration(variables.StartDelayInMilliSeconds))
	go rctUtils.BuildData(c)
	if variables.EnablePrometheus {
		go prometheus.StartServer(variables.PrometheusPort)
	}

	for variables.RctValues[0].TimeNow == "" {
		fmt.Println("Waiting for data...")
		time.Sleep(time.Millisecond * time.Duration(variables.StartDelayInMilliSeconds))
	}
	fmt.Printf("\n =========================================== \n\n")

	lc := 0
	variables.ForceUpdateHomeAssistant = true
	for {
		lc++

		if variables.ClearLoopOutput {
			clearScreen()
		}

		// Get current values
		dateNow := variables.RctValues[0].DateNow
		timeNow := variables.RctValues[0].TimeNow
		timeZone := variables.RctValues[0].TimeZoneNow
		solarGenAPowerW, _ := strconv.ParseFloat(variables.RctValues[0].Output, 32)
		solarGenBPowerW, _ := strconv.ParseFloat(variables.RctValues[1].Output, 32)
		inverterACPowerW, _ := strconv.ParseFloat(variables.RctValues[2].Output, 32)
		totalSolarPowerW, _ := strconv.ParseFloat(variables.RctValues[3].Output, 32)
		totalHouseConsumptionW := variables.TotalHouseComsumptionW
		totalGridPowerW, _ := strconv.ParseFloat(variables.RctValues[4].Output, 32)
		usingSolarPowerOnly := variables.UsingSolarPowerOnly

		jsonString := generalUtils.CreateJsonString(
			dateNow, timeNow, timeZone,
			solarGenAPowerW, solarGenBPowerW, inverterACPowerW,
			totalSolarPowerW, totalHouseConsumptionW, totalGridPowerW,
			usingSolarPowerOnly,
		)

		// Update Prometheus metrics
		if variables.EnablePrometheus {
			prometheus.UpdateMetrics(solarGenAPowerW, solarGenBPowerW, inverterACPowerW,
				totalSolarPowerW, totalHouseConsumptionW, totalGridPowerW,
				usingSolarPowerOnly, variables.SolarPowerAvailable)
		}

		// Update HomeAssistant
		if !variables.SolarPowerAvailable || variables.ForceUpdateHomeAssistant ||
			lc >= variables.HomeAssistantUpdateIntervalInOutputRefreshLoopIterations {
			updateHomeAssistant(solarGenAPowerW, solarGenBPowerW, inverterACPowerW,
				totalSolarPowerW, totalHouseConsumptionW, totalGridPowerW)
			variables.ForceUpdateHomeAssistant = false
			lc = 0
		}

		// Write to JSON file
		if variables.WriteJsonToFile {
			_, _, _, month, year := generalUtils.GetDateAndTime()
			jsonFile := filepath.Join(variables.JsonFileLocation,
				fmt.Sprintf("%s-%s%s", year, month,
					variables.JsonFileNameSuffixAfterAutogeneratedTimePrefix))
			generalUtils.WriteJsonToFile(jsonString, jsonFile)
		}

		// Display output
		if variables.OutputJson {
			displayJsonOutput(jsonString)
		} else {
			displayTextOutput(totalHouseConsumptionW)
		}

		fmt.Println()
		time.Sleep(time.Millisecond * time.Duration(variables.OutputRefreshIntervalInMilliSeconds))
	}
}

func clearScreen() {
	var cmd *exec.Cmd
	switch variables.GOOS {
	case "darwin", "linux":
		cmd = exec.Command("clear")
	case "windows":
		cmd = exec.Command("cmd", "/c", "cls")
	default:
		return
	}
	cmd.Stdout = os.Stdout
	cmd.Run()
}

func updateHomeAssistant(solarGenA, solarGenB, inverterAC, totalSolar, totalHouse, totalGrid float64) {
	state := map[bool]string{true: "on", false: "off"}

	homeassistantApi.CallHomeAssisatantApiSet(variables.ApiBoolSolarPowerAvailable,
		generalUtils.CreateJSONReaderKeyValue("state", state[variables.SolarPowerAvailable]))
	homeassistantApi.CallHomeAssisatantApiSet(variables.ApiBoolSolarPowerOnly,
		generalUtils.CreateJSONReaderKeyValue("state", state[variables.UsingSolarPowerOnly]))

	// Update numeric values
	homeassistantApi.CallHomeAssisatantApiSet(variables.ApiIntSolarGenAPowerW,
		generalUtils.CreateJSONReaderKeyValue("state", fmt.Sprintf("%.0f", solarGenA)))
	homeassistantApi.CallHomeAssisatantApiSet(variables.ApiIntSolarGenBPowerW,
		generalUtils.CreateJSONReaderKeyValue("state", fmt.Sprintf("%.0f", solarGenB)))
	homeassistantApi.CallHomeAssisatantApiSet(variables.ApiIntSolarGenTotalPowerW,
		generalUtils.CreateJSONReaderKeyValue("state", fmt.Sprintf("%.0f", inverterAC)))
	homeassistantApi.CallHomeAssisatantApiSet(variables.ApiIntPVDelivery,
		generalUtils.CreateJSONReaderKeyValue("state", fmt.Sprintf("%.0f", totalSolar)))
	homeassistantApi.CallHomeAssisatantApiSet(variables.ApiIntHouseConsumption,
		generalUtils.CreateJSONReaderKeyValue("state", fmt.Sprintf("%.0f", totalHouse)))
	homeassistantApi.CallHomeAssisatantApiSet(variables.ApiIntGridFeed,
		generalUtils.CreateJSONReaderKeyValue("state", fmt.Sprintf("%.0f", totalGrid)))
}

func displayJsonOutput(jsonString []byte) {
	var prettyJSON bytes.Buffer
	if err := json.Indent(&prettyJSON, jsonString, "", "    "); err != nil {
		fmt.Println("Error:", err)
		return
	}
	fmt.Println(prettyJSON.String())
}

func displayTextOutput(totalHouseConsumptionW float64) {
	timeStamp := time.Now().String()
	fmt.Printf("%s %s %s (%s)\n", variables.RctValues[0].DateNow,
		variables.RctValues[0].TimeNow, variables.RctValues[0].TimeZoneNow, timeStamp)

	for i, val := range variables.RctValues {
		if i == 4 {
			continue // Skip TotalGridPowerW
		}
		fmt.Printf("%s: %s\n", val.Id, val.Output)
	}

	fmt.Printf("Total house comsumption [W]: %.2f\n", totalHouseConsumptionW)

	if variables.UsingSolarPowerOnly {
		fmt.Printf("Feed to grid [W]: %s\n", strings.TrimPrefix(variables.RctValues[4].Output, "-"))
		fmt.Printf("Using solar power only: True\n")
	} else {
		fmt.Printf("Consumtion from grid [W]: %s\n", variables.RctValues[4].Output)
		fmt.Printf("Using solar power only: False\n")
	}
}
